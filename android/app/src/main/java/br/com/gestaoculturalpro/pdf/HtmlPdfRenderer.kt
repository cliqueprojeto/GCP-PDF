package br.com.gestaoculturalpro.pdf

import android.annotation.SuppressLint
import android.content.Context
import android.os.Handler
import android.os.Looper
import android.print.PdfPrinter
import android.print.PrintAttributes
import android.webkit.WebResourceRequest
import android.webkit.WebResourceResponse
import android.webkit.WebView
import android.webkit.WebViewClient
import androidx.webkit.WebViewAssetLoader
import java.io.File
import java.util.ArrayDeque

/**
 * HTML to PDF with the device's Chromium, the engine Electron's printToPDF uses on the desktop: Word, Excel,
 * PowerPoint, plain text and fiscal XML conversions produce the same layout. Jobs run one at a time on the
 * main thread in an off-screen WebView that can only read the app's own origin.
 */
class HtmlPdfRenderer(private val context: Context, private val loader: WebViewAssetLoader) {
    private class Job(val url: String, val output: File, val widthMils: Int, val heightMils: Int, val done: (String?) -> Unit)
    private val main = Handler(Looper.getMainLooper())
    private val queue = ArrayDeque<Job>()
    private var running = false

    fun render(url: String, output: File, widthMils: Int, heightMils: Int, done: (String?) -> Unit) = main.post {
        queue.add(Job(url, output, widthMils, heightMils, done))
        next()
    }

    private fun next() {
        if (running) return
        val job = queue.poll() ?: return
        running = true
        run(job) { error -> running = false; job.done(error); next() }
    }

    @SuppressLint("SetJavaScriptEnabled")
    private fun run(job: Job, finish: (String?) -> Unit) {
        val view = WebView(context)
        var finished = false
        val timeout = Runnable { if (!finished) { finished = true; view.destroy(); finish("A conversão excedeu o tempo limite.") } }
        fun complete(error: String?) { if (finished) return; finished = true; main.removeCallbacks(timeout); main.post { view.destroy() }; finish(error) }
        view.settings.apply {
            javaScriptEnabled = true // only to wait for web fonts; the documents are generated by the app
            allowFileAccess = false
            allowContentAccess = false
            blockNetworkLoads = false
            loadsImagesAutomatically = true
            textZoom = 100
        }
        // Lays out at the page width, as Chromium's desktop printing does.
        val widthPx = (job.widthMils / 1000f * 96f).toInt().coerceAtLeast(320)
        view.layout(0, 0, widthPx, (job.heightMils / 1000f * 96f).toInt().coerceAtLeast(320))
        view.webViewClient = object : WebViewClient() {
            override fun shouldInterceptRequest(view: WebView, request: WebResourceRequest): WebResourceResponse? =
                if (request.url.host == MainActivity.HOST) loader.shouldInterceptRequest(request.url) else WebResourceResponse("text/plain", "utf-8", 403, "Blocked", emptyMap(), null)
            override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest) = true
            override fun onPageFinished(view: WebView, url: String) { waitReady(view, 0) }
            private fun waitReady(view: WebView, attempt: Int) {
                view.evaluateJavascript("(document.readyState==='complete'&&(!document.fonts||document.fonts.status==='loaded')&&[...document.images].every(i=>i.complete))") { ready ->
                    if (finished) return@evaluateJavascript
                    if (ready == "true" || attempt > 100) main.postDelayed({ print(view) }, 120)
                    else main.postDelayed({ waitReady(view, attempt + 1) }, 50)
                }
            }
            private fun print(view: WebView) {
                if (finished) return
                val size = PrintAttributes.MediaSize("gcp-${job.widthMils}x${job.heightMils}", "GCP", job.widthMils, job.heightMils)
                val attributes = PrintAttributes.Builder()
                    .setMediaSize(size)
                    .setResolution(PrintAttributes.Resolution("pdf", "pdf", 600, 600))
                    .setMinMargins(PrintAttributes.Margins.NO_MARGINS)
                    .setColorMode(PrintAttributes.COLOR_MODE_COLOR)
                    .build()
                PdfPrinter(attributes).print(view.createPrintDocumentAdapter("GCP-PDF"), job.output) { error -> main.post { complete(error) } }
            }
        }
        main.postDelayed(timeout, 180_000)
        view.loadUrl(job.url)
    }
}
